<#
.SYNOPSIS
	Checks every bundled snippet (src\bin\snippets\*.nss) with shell.exe -config:check.

.DESCRIPTION
	Copies the shipped configuration (shell.nss and imports\) from BinDir to a temporary
	folder, turns the snippets on the way the app's Snippets page does (a copy in
	imports\snippets and an import line in imports\settings-app-snippets.nss, which
	shell.nss imports) and runs shell.exe -config:check: once per snippet, then with all of
	them. Any error or warning fails the check.

	settings_tests runs the same check when src\bin\shell.exe exists; this script is for
	CI, where the app's tests run before the core is built.

.PARAMETER BinDir
	The build output folder with shell.exe, shell.dll, shell.nss, imports\ and snippets\.
	Default: src\bin in this repository.
#>
[CmdletBinding()]
param([string]$BinDir)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$repo = Split-Path -Parent $PSScriptRoot
if (-not $BinDir) { $BinDir = Join-Path $repo 'src\bin' }
$BinDir = (Resolve-Path -LiteralPath $BinDir).Path
$shell = Join-Path $BinDir 'shell.exe'
$snippets = Join-Path $repo 'src\bin\snippets'
if (-not (Test-Path -LiteralPath $shell)) { throw "shell.exe not found in $BinDir" }

$dir = Join-Path ([IO.Path]::GetTempPath()) ('nsp-snippets-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $dir | Out-Null
try {
	Copy-Item -LiteralPath (Join-Path $BinDir 'shell.nss') -Destination $dir
	Copy-Item -LiteralPath (Join-Path $BinDir 'imports') -Destination (Join-Path $dir 'imports') -Recurse
	New-Item -ItemType Directory -Path (Join-Path $dir 'imports\snippets') | Out-Null
	Add-Content -LiteralPath (Join-Path $dir 'shell.nss') -Value "import 'imports/settings-app-snippets.nss'"

	$ids = @(Get-ChildItem -LiteralPath $snippets -Filter *.nss | ForEach-Object { $_.BaseName })
	if (-not $ids) { throw "no snippets in $snippets" }

	function Test-Snippets([string[]]$list) {
		$lines = @('// generated by Nilesoft Shell Pro, do not edit by hand')
		Get-ChildItem -LiteralPath (Join-Path $dir 'imports\snippets') | Remove-Item
		foreach ($id in $list) {
			Copy-Item -LiteralPath (Join-Path $snippets "$id.nss") -Destination (Join-Path $dir "imports\snippets\$id.nss")
			$lines += "import 'snippets/$id.nss'"
		}
		Set-Content -LiteralPath (Join-Path $dir 'imports\settings-app-snippets.nss') -Value $lines
		$out = Join-Path $dir 'check.json'
		$p = Start-Process -FilePath $shell -ArgumentList '-silent', '-config:check', "`"$dir\shell.nss`"", "`"-out:$out`"" `
			-Wait -PassThru -WindowStyle Hidden
		$json = Get-Content -LiteralPath $out -Raw | ConvertFrom-Json
		$problems = @($json.errors) + @($json.warnings) | Where-Object { $_ }
		if ($p.ExitCode -ne 0 -or -not $json.ok -or $problems) {
			foreach ($e in $problems) { Write-Host "  $($e.file):$($e.line):$($e.column): $($e.message)" }
			return $false
		}
		return $true
	}

	$failed = 0
	foreach ($id in $ids) {
		if (Test-Snippets @($id)) { Write-Host "ok      $id" } else { Write-Host "FAILED  $id"; $failed++ }
	}
	if (Test-Snippets $ids) { Write-Host "ok      all $($ids.Count) together" } else { Write-Host 'FAILED  all together'; $failed++ }
	if ($failed) { throw "$failed snippet check(s) failed" }
}
finally {
	Remove-Item -LiteralPath $dir -Recurse -Force -ErrorAction SilentlyContinue
}
