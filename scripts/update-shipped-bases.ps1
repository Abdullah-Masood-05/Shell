<#
.SYNOPSIS
    Writes src/settings/src/ShippedBases.inc: the text of the shipped config files with menus
    and items in them (src/bin/shell.nss and src/bin/imports/*.nss), as released in each tag
    from -Since on, where it differs from the working tree.

.DESCRIPTION
    Before 2.3.0-beta.6 the app's Menu map changed the files that came with Shell in place
    (vis=vis.remove on an item's line, a new title=, image=, menu= or pos=). An update then
    kept the user's copy of such a file as "changed by you". The app carries those changes
    over to the new version on its own (src/settings/src/CarryOver.h): it needs the version
    the user's copy started from to tell the user's changes from the release's. The version
    being installed is in the install folder; the earlier ones are these.

    Only files with menu or item declarations are kept (no language files, images.nss or
    theme.nss), each distinct text once (compared after the same normalization as
    ShippedConfigHashes.inc: no BOM, LF line ends, no trailing blanks).

    Run it after a release, with the others (update-shipped-hashes.ps1), and commit the
    result. -Check compares with the committed file and exits 1 when it is out of date.

.PARAMETER Since
    The first release whose files are kept (default v2.3.0-beta.1, the first with the Menu map).

.EXAMPLE
    pwsh scripts/update-shipped-bases.ps1
#>
[CmdletBinding()]
param(
    [string]$Since = 'v2.3.0-beta.1',
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version 3

$repo = Join-Path $PSScriptRoot '..' | Resolve-Path | Select-Object -ExpandProperty Path
$outPath = Join-Path $repo 'src/settings/src/ShippedBases.inc'
$utf8 = [System.Text.UTF8Encoding]::new($false)
# git prints the files' bytes: read them as UTF-8 (a BOM becomes U+FEFF, dropped below).
[Console]::OutputEncoding = $utf8

function Get-Normalized([string]$text) {
    if ($text.Length -gt 0 -and $text[0] -eq [char]0xFEFF) { $text = $text.Substring(1) }
    $text = $text.Replace("`r`n", "`n").Replace("`r", "`n")
    $lines = foreach ($l in $text.Split("`n")) { $l.TrimEnd(' ', "`t") }
    $joined = ($lines -join "`n").TrimEnd("`n")
    return $joined + "`n"
}

function Test-HasDeclarations([string]$text) {
    return [regex]::IsMatch($text, '(?m)^\s*(menu|item)\s*\(')
}

# Release tags (vX.Y.Z or vX.Y.Z-beta.N) from $Since on, oldest first.
function Get-Version([string]$tag) {
    if ($tag -notmatch '^v(\d+)\.(\d+)\.(\d+)(?:-beta\.(\d+))?$') { return $null }
    $beta = if ($Matches[4]) { [int]$Matches[4] } else { 100000 }
    return [long]$Matches[1] * 1e12 + [long]$Matches[2] * 1e9 + [long]$Matches[3] * 1e6 + $beta
}
$sinceVersion = Get-Version $Since
if ($null -eq $sinceVersion) { throw "not a release tag: $Since" }
$tags = git -C $repo tag --list 'v*' | Where-Object { $v = Get-Version $_; $null -ne $v -and $v -ge $sinceVersion } |
    Sort-Object { Get-Version $_ }

# The working tree's text of each file: the version the install folder will have.
$current = @{}
$binDir = Join-Path $repo 'src/bin'
$files = @('shell.nss') + (Get-ChildItem (Join-Path $binDir 'imports') -Filter *.nss -File | ForEach-Object { "imports/$($_.Name)" })
foreach ($rel in $files) {
    $text = [System.IO.File]::ReadAllText((Join-Path $binDir $rel), $utf8)
    $current[$rel] = Get-Normalized $text
}

$entries = [System.Collections.Generic.List[object]]::new()
$seen = @{}
foreach ($tag in $tags) {
    $listed = git -C $repo ls-tree -r --name-only $tag -- src/bin/shell.nss src/bin/imports
    foreach ($path in $listed) {
        if ($path -notmatch '^src/bin/(shell\.nss|imports/[^/]+\.nss)$') { continue }
        $rel = $Matches[1]
        $raw = git -C $repo show "${tag}:$path" | Out-String
        $text = Get-Normalized $raw
        if (-not (Test-HasDeclarations $text)) { continue }
        if ($current.ContainsKey($rel) -and $current[$rel] -eq $text) { continue }
        $key = "$rel`n$text"
        if ($seen.ContainsKey($key)) { continue }
        $seen[$key] = $true
        if ($text.Contains(')nss"')) { throw "$tag $rel holds )nss`"" }
        $entries.Add([pscustomobject]@{ Tag = $tag; Rel = $rel; Text = $text })
    }
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.Append("// Generated by scripts/update-shipped-bases.ps1 (since $Since): do not edit.`n")
[void]$sb.Append("// { path, text } of the shipped files with menus and items, as released, where they`n")
[void]$sb.Append("// differ from this version's. See src/settings/src/CarryOver.h.`n")
foreach ($e in $entries) {
    [void]$sb.Append("// $($e.Tag)`n{ `"$($e.Rel)`",`n")
    # Pieces of at most 8000 characters: MSVC takes no longer string literal.
    $t = $e.Text
    for ($i = 0; $i -lt $t.Length; $i += 8000) {
        $n = [Math]::Min(8000, $t.Length - $i)
        [void]$sb.Append("R`"nss($($t.Substring($i, $n)))nss`"`n")
    }
    [void]$sb.Append("},`n")
}
$out = $sb.ToString()

if ($Check) {
    $old = if (Test-Path $outPath) { (Get-Normalized ([System.IO.File]::ReadAllText($outPath, $utf8))) } else { '' }
    if ($old -ne (Get-Normalized $out)) {
        Write-Error "$outPath is out of date: run pwsh scripts/update-shipped-bases.ps1"
        exit 1
    }
    Write-Host "$outPath is up to date ($($entries.Count) texts)."
    exit 0
}
[System.IO.File]::WriteAllText($outPath, $out, $utf8)
Write-Host "Wrote $outPath ($($entries.Count) texts, $($out.Length) characters)."
