#pragma once

// OverridesWriter: the app-owned imports/settings-app.nss.
//
// The file holds only the keys the user changed, in one theme{} and one
// settings{} block, and is imported as the last line of the root shell.nss
// so its values win (later values override earlier ones key by key).
//
// The user may edit it by hand: merge() changes only the values the app
// changed and keeps everything else (comments, other statements, layout).

#include "nss/NssDocument.h"

#include <map>
#include <string>
#include <string_view>

namespace nss
{
	// canonical key ("theme.background.opacity") -> literal text ("50")
	using Overrides = std::map<std::string, std::string>;

	class OverridesWriter
	{
	public:
		// The first line of every file the app keeps in imports/ (settings-app*.nss).
		static constexpr std::string_view header = "// Nilesoft Shell Pro keeps this file. You can edit it; the app keeps your changes.";
		// `header`, or the "// generated by Nilesoft Shell ..., do not edit" line of older versions.
		static bool isHeader(std::string_view line);
		// Puts `header` in place of an older one on the first line. True when it changed.
		static bool updateHeader(NssDocument &doc);
		static constexpr std::string_view relativePath = "imports/settings-app.nss";

		// The full file text, using `eol` line endings. Keys are written in
		// schema order; unknown keys after the known ones, alphabetically.
		static std::string generate(const Overrides &overrides, Eol eol = Eol::CRLF);

		// A document for the file, keeping the encoding/BOM/EOL of `existing`
		// when there is one.
		static NssDocument generateDocument(const Overrides &overrides, const NssDocument *existing = nullptr);

		// `existing` with `after` applied in place: a changed value is replaced
		// where it is, a new one goes at the end of its theme{}/settings{} block
		// (or a new block), a removed one is deleted. Comments and everything
		// else in the file stay as they are.
		static NssDocument merge(const NssDocument &existing, const Overrides &after);

		// The overrides an existing settings-app.nss holds (last value wins).
		static Overrides read(const NssDocument &doc);

		// Makes `import '<relPath>'` the last statement of the root document,
		// removing other imports of the same file. Returns true when the
		// document changed; calling it again changes nothing.
		static bool ensureImportedLast(NssDocument &root, std::string_view relPath = relativePath);

		// True when `importValue` (an evaluated import path) names `relPath`.
		static bool samePath(std::string_view importValue, std::string_view relPath);
	};
}
